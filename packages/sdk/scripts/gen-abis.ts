/**
 * ABIs from forge `out/` → src/abis/*.ts (as const, for viem type inference).
 * Run after `forge build`: `pnpm --filter @pantado/sdk gen:abis`.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { findRepoRoot } from "@pantado/shared";

export const CONTRACTS = [
  "IndexFactory",
  "IndexVault",
  "IndexLens",
  "AssetRegistry",
  "PriceOracle",
  "FeeSplitter",
  "Rebalancer",
  "StockVenue",
  "TokenVenue",
  "DexVenue",
  "PToken",
  "SwapRouter",
  "TestERC20",
] as const;

const lowerFirst = (s: string): string => s.charAt(0).toLowerCase() + s.slice(1);

function main(): void {
  const root = findRepoRoot();
  const outDir = join(root, "packages/sdk/src/abis");
  mkdirSync(outDir, { recursive: true });
  const exports: string[] = [];
  for (const name of CONTRACTS) {
    const artifact = join(root, "contracts/out", `${name}.sol`, `${name}.json`);
    if (!existsSync(artifact)) throw new Error(`missing ${artifact} — run forge build`);
    const { abi } = JSON.parse(readFileSync(artifact, "utf8")) as { abi: unknown[] };
    const constName = `${lowerFirst(name)}Abi`;
    writeFileSync(
      join(outDir, `${name}.ts`),
      `// GENERATED by packages/sdk/scripts/gen-abis.ts from contracts/out — do not edit.\nexport const ${constName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
    );
    exports.push(`export { ${constName} } from "./${name}.js";`);
  }
  writeFileSync(join(outDir, "index.ts"), `// GENERATED — do not edit.\n${exports.join("\n")}\n`);
  console.log(`wrote ${CONTRACTS.length} ABIs to ${outDir}`);
}

main();
